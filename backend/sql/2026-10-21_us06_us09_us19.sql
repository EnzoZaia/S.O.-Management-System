BEGIN;

CREATE TABLE IF NOT EXISTS evidencia_ordem (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id integer NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    usuario_id bigint NOT NULL REFERENCES usuario (id),
    sequencia integer NOT NULL,
    tipo_arquivo varchar(10) NOT NULL,
    tipo_conteudo varchar(60) NOT NULL,
    caminho_arquivo varchar(255) NOT NULL,
    nome_original varchar(255) NOT NULL,
    tamanho_bytes bigint NOT NULL,
    data_envio timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT evidencia_ordem_ordem_servico_id_sequencia_key UNIQUE (ordem_servico_id, sequencia),
    CONSTRAINT evidencia_ordem_tipo_arquivo_check CHECK (tipo_arquivo IN ('IMAGEM', 'VIDEO')),
    CONSTRAINT evidencia_ordem_tamanho_bytes_check CHECK (tamanho_bytes > 0)
);
CREATE INDEX IF NOT EXISTS idx_evidencia_ordem_os ON evidencia_ordem (ordem_servico_id);

CREATE TABLE IF NOT EXISTS notificacao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    ordem_servico_id integer NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    tipo varchar(40) NOT NULL,
    titulo varchar(150) NOT NULL,
    mensagem text NOT NULL,
    lida boolean NOT NULL DEFAULT false,
    data_criacao timestamptz NOT NULL DEFAULT now(),
    data_leitura timestamptz NULL
);
CREATE INDEX IF NOT EXISTS idx_notificacao_usuario ON notificacao (usuario_id, lida, data_criacao DESC);

CREATE TABLE IF NOT EXISTS ordem_servico_ativo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id integer NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    ativo_id integer NOT NULL REFERENCES ativo (id),
    resultado varchar(20) NOT NULL DEFAULT 'PENDENTE',
    motivo text NULL,
    data_resultado timestamptz NULL,
    usuario_resultado_id bigint NULL REFERENCES usuario (id),
    CONSTRAINT ordem_servico_ativo_ordem_servico_id_ativo_id_key UNIQUE (ordem_servico_id, ativo_id),
    CONSTRAINT ordem_servico_ativo_resultado_check CHECK (resultado IN ('PENDENTE', 'CONCLUIDO', 'NAO_CONCLUIDO')),
    CONSTRAINT ordem_servico_ativo_motivo_check CHECK (resultado <> 'NAO_CONCLUIDO' OR motivo IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_ordem_servico_ativo_ativo ON ordem_servico_ativo (ativo_id, resultado);

CREATE TABLE IF NOT EXISTS checklist_item_ativo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_ativo_id bigint NOT NULL REFERENCES ordem_servico_ativo (id) ON DELETE CASCADE,
    codigo_item integer NOT NULL,
    descricao varchar(255) NOT NULL,
    resultado varchar(20) NOT NULL DEFAULT 'PENDENTE',
    motivo text NULL,
    data_resposta timestamptz NULL,
    usuario_id bigint NULL REFERENCES usuario (id),
    CONSTRAINT checklist_item_ativo_item_key UNIQUE (ordem_servico_ativo_id, codigo_item),
    CONSTRAINT checklist_item_ativo_resultado_check CHECK (resultado IN ('PENDENTE', 'EXECUTADO', 'NAO_EXECUTADO')),
    CONSTRAINT checklist_item_ativo_motivo_check CHECK (resultado <> 'NAO_EXECUTADO' OR motivo IS NOT NULL)
);

COMMIT;
