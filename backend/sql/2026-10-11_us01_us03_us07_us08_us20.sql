BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS solicitante_tipo_identificador_vinculo_key
    ON solicitante (tipo_vinculo, identificador_vinculo);

CREATE TABLE IF NOT EXISTS os_participante (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id integer NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    usuario_id bigint NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    data_vinculo timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT os_participante_ordem_servico_id_usuario_id_key UNIQUE (ordem_servico_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS idx_os_participante_usuario ON os_participante (usuario_id);

CREATE TABLE IF NOT EXISTS evidencia_validacao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validacao_atendimento_id integer NOT NULL REFERENCES validacao_atendimento (id) ON DELETE CASCADE,
    caminho_arquivo varchar(255) NOT NULL,
    nome_original varchar(255) NOT NULL,
    data_upload timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_evidencia_validacao_validacao ON evidencia_validacao (validacao_atendimento_id);

CREATE TABLE IF NOT EXISTS auditoria_usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_alvo_id bigint NOT NULL REFERENCES usuario (id),
    autor_usuario_id bigint NOT NULL REFERENCES usuario (id),
    campo varchar(50) NOT NULL,
    valor_anterior varchar(255) NULL,
    valor_novo varchar(255) NULL,
    data_registro timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_alvo ON auditoria_usuario (usuario_alvo_id, data_registro DESC);

COMMIT;
